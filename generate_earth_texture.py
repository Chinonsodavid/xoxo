import math, random
from PIL import Image, ImageDraw, ImageFilter

W, H = 2048, 1024
img = Image.new("RGBA", (W, H), (6, 8, 14, 255))
draw = ImageDraw.Draw(img)

# 1. Soft Ocean Shading & Deep Blues
for y in range(H):
    # slight gradient from equator to poles
    lat = 90.0 - (y / H) * 180.0
    factor = math.cos(math.radians(lat))
    b = int(14 + 8 * factor)
    g = int(8 + 5 * factor)
    r = int(6 + 3 * factor)
    draw.line([(0, y), (W, y)], fill=(r, g, b, 255))

# 2. Subtle Coordinate Grid Lines (Graticules)
for lat in range(-75, 90, 15):
    y = int((90 - lat) * (H / 180.0))
    c = (197, 160, 89, 45) if lat == 0 else (255, 255, 255, 12)
    w = 2 if lat == 0 else 1
    draw.line([(0, y), (W, y)], fill=c, width=w)

for lon in range(-180, 180, 15):
    x = int((lon + 180) * (W / 360.0))
    c = (197, 160, 89, 45) if lon == 0 else (255, 255, 255, 12)
    w = 2 if lon == 0 else 1
    draw.line([(x, 0), (x, H)], fill=c, width=w)

def to_xy(coords):
    return [((lon + 180.0) * (W / 360.0), (90.0 - lat) * (H / 180.0)) for lon, lat in coords]

